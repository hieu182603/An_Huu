import { test, expect, type Browser, type Page } from "@playwright/test";
import { readFileSync } from "node:fs";
const fixture = JSON.parse(readFileSync(new URL("../../.tmp/remediation/browser-fixture.json", import.meta.url), "utf8"));
async function login(browser: Browser, actor: string) {
  const context = await browser.newContext(), page = await context.newPage();
  await page.goto("/login");
  await page.locator("#login-email").fill(fixture.actors[actor].email);
  await page.locator("#login-password").fill(fixture.password);
  await page.locator('form button[type="submit"]').click();
  await expect(page).toHaveURL(/\/(user|admin)\/|\/onboarding/, { timeout: 30000 });
  return { context, page };
}
let recommendationId = "";
async function decision(page: Page, name: string) {
  await page.getByLabel("Lý do quyết định").fill("Kiểm tra độc lập trên dữ liệu mô phỏng");
  await page.locator(`[data-recommendation-id="${recommendationId}"]`).getByRole("button", { name, exact: true }).click();
  await expect(page.getByText("Đang tải…", { exact: true })).toHaveCount(0);
}
