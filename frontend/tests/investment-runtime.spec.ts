test("saved plan opens from PostgreSQL and browser runs the real financial simulation", async ({ browser }) => {
  const client = await login(browser, "userA");
  await client.page.goto("/user/plan");
  const risk = client.page.getByTestId("risk-analysis");
  await risk.getByLabel("Số đường đi mô phỏng").fill("10");
  await risk.getByLabel("ID bộ dữ liệu đã công bố (tùy chọn)").fill(fixture.marketVersionId);
  const responsePromise = client.page.waitForResponse(r => r.url().endsWith("/retirement/risk/simulation") && r.request().method() === "POST");
  await risk.getByRole("button", { name: "Chạy mô phỏng", exact: true }).click();
  const response = await responsePromise;
  expect(response.status()).toBe(200);
  expect((await response.json()).data.status).toBe("READY");
  await expect(risk.getByTestId("simulation-probability")).toBeVisible();
  await client.page.reload();
  await expect(client.page.getByTestId("risk-analysis")).toBeVisible();
  await client.context.close();
});

